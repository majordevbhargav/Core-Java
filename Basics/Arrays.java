public class Arrays {
    public static void main(String args[]){
        int []arr={1,2,3,4,5};
        int n=arr.length;
        for(int i=0;i<n;i++){
            System.out.println(arr[i]);
        }
        String [] names={"Dev","Rahul","Mukesh"};
        for(int i=0;i<names.length;i++){
            System.out.println(names[i]);
        }
    }
}
